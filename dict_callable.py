class Dictionary:
    """ Обертка над словарем, делающая его экземпляром вызываемым (callable).
    Этот класс позволяет обращаться к словарю как к функции,
    используя синтаксис instance(key). В отличие от прямого доступа через
    квадратные скобки (dict[key]), вызов через __call__ не выбрасывает
    исключение KeyError при отсутствии ключа, а возвращает None.
    Это делает его удобным для использования в качестве стратегии или коллбэка,
    где требуется безопасный доступ к данным. """
    def __init__(self, dictionary):
        """ Инициализирует обертку, сохраняя ссылку на переданный словарь. """
        self.dictionary = dictionary

    def __call__(self, key):
        """ Возвращает значение по ключу из внутреннего словаря. """
        if key in self.dictionary:
            return self.dictionary[key]


dictionary = Dictionary({1: 2, 2: 1, 3: 3})
print(dictionary(2))